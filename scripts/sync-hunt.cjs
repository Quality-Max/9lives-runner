// Publish the picture-hunt game to the website as a static page that replays
// recorded live Jev + 9lives runs. demo/jev stays the source of truth.
//
//   node scripts/sync-hunt.cjs                 regenerate the page and rooms
//   node scripts/sync-hunt.cjs --check         fail if the site copy is stale
//   node scripts/sync-hunt.cjs --import DIR... replace replays from local runs
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } = require('node:fs');
const { join, relative, resolve } = require('node:path');

const root = resolve(__dirname, '..');
const site = resolve(root, 'website/public');
const replays = resolve(site, 'hunt/replays');
const scenarios = ['cats', 'dogs', 'mice', 'striped'];
const variants = ['healthy', 'broken'];

function once(text, old, next) {
  assert.equal(text.split(old).length - 1, 1, `Expected exactly one ${JSON.stringify(old)}`);
  return text.replace(old, () => next);
}

// Mirrors catFixture in demo/jev/cats.go, so hashes match the recorded runs.
function room(scenario, broken = false) {
  let html = once(readFileSync(resolve(root, 'demo/jev/cat-room.html'), 'utf8'), 'data-scenario="cats"', `data-scenario="${scenario}"`);
  if (broken) html = once(html, 'data-broken="false"', 'data-broken="true"');
  return html;
}

function page() {
  let html = readFileSync(resolve(root, 'demo/jev/cats.html'), 'utf8');
  for (const [old, next] of [
    ['<!doctype html>\n', '<!doctype html>\n<!-- Generated by scripts/sync-hunt.cjs from demo/jev/cats.html. Do not edit. -->\n'],
    ['content="__DEMO_SESSION__"', 'content=""'],
    ['<meta name="demo-mode" content="local">', '<meta name="demo-mode" content="replay">'],
    ["url('/assets/heading.woff2')", "url('/brand/space-grotesk-latin.woff2')"],
    ["url('/assets/body.woff2')", "url('/brand/dm-sans-latin.woff2')"],
    ['<a href="/" aria-label="Back to the checkout demo"><img src="/assets/logo.svg" alt="QualityMax"></a>', '<a href="/" aria-label="9lives home"><img src="/brand/logo-wordmark-color.svg" alt="QualityMax"></a>'],
    ['<a href="/">Notebook shop ↗</a>', '<a href="/">Home</a>'],
    ['src="/shop?scenario=cats"', 'src="/hunt/rooms/cats.html"'],
    ['</body></html>', '<script src="/qualitymax-analytics.js" defer></script></body></html>'],
  ]) html = once(html, old, next);
  return html;
}

function expected() {
  const files = { 'hunt.html': page() };
  for (const scenario of scenarios) files[`hunt/rooms/${scenario}.html`] = room(scenario);
  return files;
}

const sha256 = text => createHash('sha256').update(text).digest('hex');
const readJSON = file => JSON.parse(readFileSync(file, 'utf8'));

// Published JSON must not reveal local machine paths.
function assertPortable(value, where) {
  if (typeof value === 'string') assert.ok(!value.startsWith('/') && !/^[A-Za-z]:[\\/]/.test(value) && !value.includes('/Users/') && !value.includes('/home/'), `${where} contains a local path`);
  else if (value && typeof value === 'object') for (const [key, item] of Object.entries(value)) assertPortable(item, `${where}.${key}`);
}

function checkReplays() {
  for (const scenario of scenarios) for (const variant of variants) {
    const dir = join(replays, `${scenario}-${variant}`), name = `${scenario}-${variant}`;
    const run = readJSON(join(dir, 'replay.json'));
    assert.equal(run.scenario, scenario, name);
    assert.equal(run.broken, variant === 'broken', name);
    assert.equal(run.outcome, variant === 'broken' ? 'failed' : 'passed', `${name} outcome`);
    assert.equal(run.fixtureSHA256, sha256(room(scenario, run.broken)), `${name} was recorded against a different game; re-record it`);
    assert.equal(run.receipts.length, 1, name);
    assert.ok(run.receipts[0].validated && run.receipts[0].executedTests === 1 && run.receipts[0].status === run.outcome, `${name} receipt`);
    assert.equal(run.jev.status, 'answered', `${name} Jev record`);
    assert.ok(run.steps.length > 0, name);
    for (const step of run.steps) assert.ok(/^frame-\d+\.png$/.test(step.image) && existsSync(join(dir, step.image)), `${name} ${step.image}`);
    assert.equal(readdirSync(dir).filter(file => file.endsWith('.png')).length, run.steps.length, `${name} frames`);
    for (const file of ['replay.json', 'receipt.json', 'jev-record.json']) assertPortable(readJSON(join(dir, file)), `${name}/${file}`);
  }
}

// Same observed geometry as demo/jev/picture-hunt.spec.mjs.
async function spotBoxes(browser, html) {
  const page = await browser.newPage({ viewport: { width: 850, height: 600 }, deviceScaleFactor: 1 });
  await page.route('**/*', route => route.abort());
  await page.setContent(html);
  const boxes = [];
  for (let id = 0; id < 9; id++) {
    const b = await page.locator(`[data-target="${id}"]`).boundingBox();
    boxes.push({ X: b.x / 8.5, Y: b.y / 6, Width: b.width / 8.5, Height: b.height / 6 });
  }
  await page.close();
  return boxes;
}

const close = (a, b) => (a === null && b === null) || (a && b && ['X', 'Y', 'Width', 'Height'].every(k => Math.abs(a[k] - b[k]) < 0.01));
const portable = value => JSON.parse(JSON.stringify(value, (_, item) => typeof item === 'string' ? item.replaceAll(root + '/', '') : item));

async function importRuns(dirs) {
  const { chromium } = require('playwright');
  const browser = await chromium.launch();
  try {
    for (const dir of dirs.map(d => resolve(d))) {
      const input = readJSON(join(dir, 'input.json')), summary = readJSON(join(dir, 'summary.json'));
      const record = readJSON(join(dir, 'jev-record.json')), progress = readJSON(join(dir, 'progress.json'));
      const variant = input.broken ? 'broken' : 'healthy', name = `${input.scenario}-${variant}`;
      assert.ok(scenarios.includes(input.scenario) && input.live === true, `${dir}: only live runs of the four levels`);
      const fixture = room(input.scenario, input.broken);
      assert.equal(input.fixtureSHA256, sha256(fixture), `${dir}: recorded against a different game`);
      // A planted bug must fail on an attributed assertion, never on setup or environment.
      const [only] = summary.receipts;
      assert.ok(summary.receipts.length === 1 && only.validated && only.executedTests === 1, `${dir}: unvalidated run`);
      if (input.broken) assert.ok(summary.outcome === 'failed' && only.status === 'failed' && only.failures?.length === 1 && only.failures[0].class === 'assertion', `${dir}: not an assertion failure`);
      else assert.ok(summary.outcome === 'passed' && summary.complete && only.status === 'passed', `${dir}: did not pass`);
      assert.equal(record.status, 'answered', `${dir}: Jev did not answer`);
      // The spec writes frame-N for event N; the click outline follows the clicked spot.
      const boxes = await spotBoxes(browser, fixture);
      let target = null;
      const steps = progress.events.map((event, i) => {
        const click = /^Clicking hiding spot (\d)…$/.exec(event.message);
        if (click) target = boxes[Number(click[1]) - 1];
        else if (!['checked', 'failed'].includes(event.stage)) target = null;
        assert.ok(existsSync(join(dir, `frame-${i}.png`)), `${dir}: missing frame-${i}.png`);
        return { stage: event.stage, message: event.message, found: event.found, checked: event.checked, image: `frame-${i}.png`, target };
      });
      assert.equal(steps.length, readdirSync(dir).filter(file => /^frame-\d+\.png$/.test(file)).length, `${dir}: frames and events differ`);
      assert.ok(close(steps.at(-1).target, progress.target), `${dir}: reconstructed outline differs from the recorded one`);
      const out = join(replays, name);
      rmSync(out, { recursive: true, force: true });
      mkdirSync(out, { recursive: true });
      for (const step of steps) copyFileSync(join(dir, step.image), join(out, step.image));
      const receipt = portable(summary);
      writeFileSync(join(out, 'receipt.json'), JSON.stringify(receipt, null, 2) + '\n');
      writeFileSync(join(out, 'jev-record.json'), JSON.stringify(record, null, 2) + '\n');
      const receipts = receipt.receipts.map(({ status, validated, executedTests, failureCount, durationMs }) => ({ status, validated, executedTests, failureCount, durationMs }));
      const jev = { status: record.status, model: record.model, requestCount: record.requestCount, questionCount: record.questionCount, usage: record.usage };
      writeFileSync(join(out, 'replay.json'), JSON.stringify({ version: 1, scenario: input.scenario, broken: input.broken, recordedAt: summary.finishedAt, runId: summary.runId, outcome: summary.outcome, fixtureSHA256: input.fixtureSHA256, jev, receipts, steps }, null, 2) + '\n');
      console.log(`Imported ${name} from ${relative(root, dir)}`);
    }
  } finally { await browser.close(); }
}

async function main(args) {
  if (args[0] === '--import') return importRuns(args.slice(1));
  const files = expected();
  if (args[0] === '--check') {
    const stale = Object.entries(files).filter(([file, text]) => !existsSync(join(site, file)) || readFileSync(join(site, file), 'utf8') !== text).map(([file]) => file);
    assert.deepEqual(stale, [], 'Run node scripts/sync-hunt.cjs to update the website copy');
    checkReplays();
    return;
  }
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(resolve(site, file, '..'), { recursive: true });
    writeFileSync(join(site, file), text);
  }
}

module.exports = { expected, checkReplays, room };
if (require.main === module) main(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
